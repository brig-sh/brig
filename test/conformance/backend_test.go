// A record gives the reason for what its own run saw. On Linux hull's gateway
// did not run, so its reset is no reason for an unproven metadata case there;
// on hvi it is the reason.
func TestUnprovenReasonIsTheBackendsOwn(t *testing.T) {
	c := caseByID(t, "metadata")
	for backend, want := range map[string]string{
		"nerdctl": "a host outside a cloud has no metadata service",
		"hvi":     "hull's gateway resets every connection to 169.254.0.0/16, with a policy or without one",
	} {
		if got := c.on(backend).unprovenWhy; got != want {
			t.Errorf("%s: %q, want %q", backend, got, want)
		}
	}
	if strings.Contains(c.on("nerdctl").unprovenWhy, "hull") {
		t.Error("the nerdctl reason names hull")
	}
}

// What goes into the record's table from the bundle, or from a flag, cannot
// break the table or carry a home path into a committed record.
func TestRecordTableHoldsWhatTheBundleSays(t *testing.T) {
	f, s := nerdctlSuite(t)
	f.pinsOut = strings.Replace(fakePins, "KERNEL_SOURCE="+fakeSource, "KERNEL_SOURCE=a|b", 1)
	s.brigCtl = "/home/someone/.local/share/brig/data/bin/brig-ctl"
	f.pinsCode = 0
	out := run(t, s).markdown()
	if !strings.Contains(out, `built from a\|b`) {
		t.Errorf("a pipe in the bundle's pins is not escaped:\n%s", out)
	}
	if strings.Contains(out, "/home/someone") {
		t.Errorf("the record carries the brig-ctl path:\n%s", out)
	}
	// brig exec is a retired spelling, so the row carries the marker
	// script/check-retired-spellings.sh reads for a doc that names one.
	if !strings.Contains(out, "| probes ran under | `brig exec` <!-- retired-ok --> |") {
		t.Errorf("the record does not say which verb the probes ran under:\n%s", out)
	}

	f.pinsCode = 127
	out = run(t, s).markdown()
	if strings.Contains(out, "/home/someone") {
		t.Errorf("the record carries the brig-ctl path from its error:\n%s", out)
	}
}

