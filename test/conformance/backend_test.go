// The reason an unproven case gives is the one its own run's backend has, all
// the way into the record. Taking it from the case alone would give the hvi
// record the Linux reason, and lose the hull clause without anything failing.
func TestRecordGivesTheBackendsOwnUnprovenReason(t *testing.T) {
	for backend, want := range map[string]string{
		"hvi":     "hull's gateway resets every connection to 169.254.0.0/16",
		"nerdctl": "a host outside a cloud has no metadata service",
	} {
		t.Run(backend, func(t *testing.T) {
			f, s := nerdctlSuite(t)
			if backend == "hvi" {
				f = newFake(t)
				s = newSuite(t, f)
			}
			well := f.answer
			f.answer = func(policy string, env, args []string, n int) outcome {
				if policy == noPolicy && caseFor(t, s, policy, env, args).id == "metadata" {
					return timedOut
				}
				return well(policy, env, args, n)
			}
			rep := run(t, s)
			var row string
			for _, line := range strings.Split(rep.markdown(), "\n") {
				if strings.HasPrefix(line, "| `metadata` |") {
					row = line
				}
			}
			if !strings.Contains(row, "unproven") || !strings.Contains(row, want) {
				t.Errorf("the metadata row does not give %q:\n%s", want, row)
			}
			if backend == "nerdctl" && strings.Contains(row, "hull") {
				t.Errorf("the nerdctl record cites hull:\n%s", row)
			}
		})
	}
}

// The rootless bundle and the plain one ship under one version, and their
// guests reach the network on different paths. Each gets a record of its own,
// so a run of one never overwrites the other's.
func TestRootlessAndPlainBundlesAreFiledApart(t *testing.T) {
	paths := map[string]string{}
	for name, rootless := range map[string]string{"rootless": "true", "plain": "false"} {
		f, s := nerdctlSuite(t)
		f.pinsOut = strings.Replace(fakePins, "ROOTLESS=true", "ROOTLESS="+rootless, 1)
		rep := run(t, s)
		paths[name] = recordPath(s.backend, rep.version(), rep.variant())
		if strings.Contains(rep.markdown(), "v0.1.0-rc17, rootless\n") != (name == "rootless") {
			t.Errorf("%s: the title says rootless %v", name, name != "rootless")
		}
	}
	if paths["rootless"] != "docs/manual-tests/egress-conformance-nerdctl-v0.1.0-rc17-rootless.md" ||
		paths["plain"] != "docs/manual-tests/egress-conformance-nerdctl-v0.1.0-rc17.md" {
		t.Errorf("filed at %v", paths)
	}
}

