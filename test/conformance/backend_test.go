// nerdctlSuite is a suite on Linux, under the environment the runtime
// bundle's brig-env.sh sets.
func nerdctlSuite(t *testing.T) (*fakeBrig, *suite) {
	t.Helper()
	f := newFake(t)
	f.versionOut = fakeNerdctl + "\n"
	f.pinsOut = fakePins
	s := newSuite(t, f)
	s.backend, s.runtime, s.brigCtl = "nerdctl", "nerdctl", "brig-ctl"
	s.env = append(s.env, "BRIG_BOOT_ASSETS=/home/u/.local/share/brig/data/share/guest",
		"CONTAINERD_ADDRESS=unix:///run/containerd/containerd.sock")
	return f, s
}

// On Linux the runtime is the bundle install.sh pins, so the record is filed
// under the bundle's version and names the parts of it a boot goes through,
// and the nft that enforces the policy.
func TestNerdctlRunIsFiledUnderTheBundle(t *testing.T) {
	_, s := nerdctlSuite(t)
	rep := run(t, s)
	if rep.failed() {
		t.Fatalf("a well-behaved guest failed on nerdctl: %v", rep.problems)
	}
	if got := recordPath(s.backend, rep.version(), rep.variant()); got != "docs/manual-tests/egress-conformance-nerdctl-v0.1.0-rc17-rootless.md" {
		t.Errorf("filed at %q", got)
	}
	out := rep.markdown()
	for _, want := range []string{
		"# Egress conformance: nerdctl, v0.1.0-rc17, rootless\n",
		"| backend | `nerdctl` |",
		"| runtime | `" + fakeNerdctl + "` |",
		"| runtime bundle | `v0.1.0-rc17, generic-boot, rootless` |",
		"| containerd | `v2.3.5` |",
		"| urunc | `urunc-dev/urunc@0b1ef07229d678e7cbb3f61e12a8efcdd5070a8a` |",
		"| rootlesskit | `v3.2.0` |",
		"| nftables | `" + fakeNFT + "` |",
		"| boot assets | `a local directory, from BRIG_BOOT_ASSETS. The runtime bundle's own copy is built from " + fakeSource + "` |",
		"| image digest | `" + fakeDigest + "` |",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("record lacks %q:\n%s", want, out)
		}
	}
	// hvi is a macOS backend, and a row for it here would claim it booted.
	if strings.Contains(out, "| hvi |") {
		t.Errorf("a nerdctl record names hvi:\n%s", out)
	}
}

// brig ignores a profile's hypervisor on Linux, and BRIG_HYPERVISOR with it.
// A profile that named one would read as if it chose something. On hvi both
// still name it, since that is what picks the backend there.
func TestOnlyHviAsksForAHypervisor(t *testing.T) {
	for backend, want := range map[string]string{"hvi": "hvi", "nerdctl": ""} {
		t.Run(backend, func(t *testing.T) {
			f := newFake(t)
			s := newSuite(t, f)
			s.backend = backend
			root := t.TempDir()
			env, err := s.prepare(root)
			if err != nil {
				t.Fatal(err)
			}
			b, err := os.ReadFile(filepath.Join(root, "profiles", profileName+".yaml"))
			if err != nil {
				t.Fatal(err)
			}
			var p map[string]any
			if err := yaml.Unmarshal(b, &p); err != nil {
				t.Fatal(err)
			}
			got, _ := p["hypervisor"].(string)
			if got != want {
				t.Errorf("the profile asks for hypervisor %q, want %q", got, want)
			}
			if got := envValue(env, "BRIG_HYPERVISOR"); got != want {
				t.Errorf("brig runs with BRIG_HYPERVISOR=%q, want %q", got, want)
			}
			if p["genericBoot"] != true {
				t.Errorf("the profile does not boot the image as it is: %v", p)
			}
		})
	}
}

// A nerdctl the bundle did not install still runs the suite. The record says
// there was no bundle, and it is filed under the nerdctl version, so it can
// never stand in for a bundle's record.
func TestNerdctlWithoutABundleIsFiledUnderNerdctl(t *testing.T) {
	f, s := nerdctlSuite(t)
	f.pinsCode = 127
	rep := run(t, s)
	if rep.failed() {
		t.Fatalf("a run with no bundle failed: %v", rep.problems)
	}
	if got := rep.version(); got != "2.3.5" {
		t.Errorf("filed under %q, want the nerdctl version", got)
	}
	out := rep.markdown()
	if !strings.Contains(out, "| runtime bundle | `none: brig-ctl version: exit 127: brig-ctl: not found` |") {
		t.Errorf("the record does not say there was no bundle:\n%s", out)
	}
	if !strings.Contains(out, "| boot assets | `a local directory, from BRIG_BOOT_ASSETS` |") {
		t.Errorf("with no pins the record still credits a bundle with the boot assets:\n%s", out)
	}
}

// Pins that name no bundle version are not a bundle. Filing a record under
// another field, or under nothing, would put it where the next bundle's goes.
func TestPinsWithoutABundleVersionAreNoBundle(t *testing.T) {
	f, s := nerdctlSuite(t)
	f.pinsOut = "# nothing pinned\nNERDCTL_VERSION=v2.3.5\n"
	rep := run(t, s)
	if rep.bundle != "" || rep.version() != "2.3.5" {
		t.Errorf("bundle %q, filed under %q", rep.bundle, rep.version())
	}
}

// Without BRIG_BOOT_ASSETS brig fetches the bundle with oras and writes
// provenance.json beside it, which is the record of what it fetched. The
// directory is under the user's home, and stays out of the record.
func TestNerdctlAssetsFromWhatBrigFetched(t *testing.T) {
	_, s := nerdctlSuite(t)
	var env []string
	for _, kv := range s.env {
		if !strings.HasPrefix(kv, "BRIG_BOOT_ASSETS=") {
			env = append(env, kv)
		}
	}
	data := t.TempDir()
	s.env = append(env, "XDG_DATA_HOME="+data)
	dir := filepath.Join(data, "brig", "assets")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	rec := `{"ref":"ghcr.io/nofireai/hull-assets:linux-amd64","digest":"sha256:aa","verifiedDigest":"sha256:aa","files":{}}`
	if err := os.WriteFile(filepath.Join(dir, "provenance.json"), []byte(rec), 0o644); err != nil {
		t.Fatal(err)
	}
	out := run(t, s).markdown()
	if !strings.Contains(out, "| boot assets | `ghcr.io/nofireai/hull-assets:linux-amd64, verified sha256:aa` |") {
		t.Errorf("the record does not name what brig fetched:\n%s", out)
	}
	if strings.Contains(out, data) {
		t.Errorf("the record carries the asset directory:\n%s", out)
	}
}

// A backend the runner does not know is a failed run that boots nothing, and
// a usage error at the command line. Running the hvi cases against it would
// judge a runtime nobody measured.
func TestUnknownBackendBootsNothing(t *testing.T) {
	f := newFake(t)
	s := newSuite(t, f)
	s.backend = "qemu"
	rep := run(t, s)
	if !rep.failed() || len(rep.problems) == 0 || !strings.Contains(rep.problems[0], "hvi and nerdctl") {
		t.Fatalf("problems %v, want a refusal naming the backends there are", rep.problems)
	}
	if calls := f.brigCalls("run"); len(calls) != 0 {
		t.Errorf("booted on an unknown backend: %v", calls)
	}

	var stdout, stderr bytes.Buffer
	if code := mainErr([]string{"-brig", "brig", "-probe", "p", "-backend", "qemu"}, &stdout, &stderr); code != 2 {
		t.Errorf("exit %d, want 2", code)
	}
	if !strings.Contains(stderr.String(), "hvi and nerdctl") {
		t.Errorf("the usage error does not name the backends: %q", stderr.String())
	}
}

// nerdctl refuses a pty with no terminal behind it, and brig sh asks for one
// whatever brig is attached to (#335), so on nerdctl every probe goes through
// brig exec, which asks only from a terminal. hvi keeps brig sh, the path its
// records were measured on.
func TestEachBackendProbesThroughAVerbThatRunsWithoutATerminal(t *testing.T) {
	for backend, want := range map[string]string{"hvi": "sh", "nerdctl": "exec"} {
		t.Run(backend, func(t *testing.T) {
			f, s := nerdctlSuite(t)
			if backend == "hvi" {
				f = newFake(t)
				s = newSuite(t, f)
			}
			if rep := run(t, s); rep.failed() {
				t.Fatalf("a well-behaved guest failed: %v", rep.problems)
			}
			other := map[string]string{"sh": "exec", "exec": "sh"}[want]
			if n := len(f.brigCalls(other)); n != 0 {
				t.Errorf("%d probes went through brig %s", n, other)
			}
			if len(f.brigCalls(want)) == 0 {
				t.Errorf("no probe went through brig %s", want)
			}
		})
	}
}

func TestNerdctlExitIsTheGuestCommands(t *testing.T) {
	line := `time="2026-10-23T01:48:44+03:00" level=fatal msg="exec failed with exit code 3"`
	for _, tc := range []struct {
		stderr string
		code   int
		want   int
	}{
		{line, 1, 3},
		{"exec failed with exit code 1\n" + line, 1, 3},
		{"brig: no such sandbox", 1, 1},
		{line, 0, 0},
		{line, 3, 3},
		{"exec failed with exit code 99999999999999999999", 1, 1},
		// The line is matched whole, in both forms nerdctl logs it in.
		{`FATA[0000] exec failed with exit code 42`, 1, 42},
		{"the guest said: exec failed with exit code 9", 1, 1},
		{`curl: time="x" level=fatal msg="exec failed with exit code 9"`, 1, 1},
		{`time="2026-10-23T01:48:44+03:00" level=fatal msg="exec failed with exit code 3 and more"`, 1, 1},
	} {
		if got := nerdctlExit(tc.stderr, tc.code); got != tc.want {
			t.Errorf("nerdctlExit(%q, %d) = %d, want %d", tc.stderr, tc.code, got, tc.want)
		}
	}
}

// Without a policy, curl through the host listener connects and then fails,
// so the probe exits 3. nerdctl reports that as 1 (#469), which disagreed with
// the probe line and threw out the one case that shows the proxy path is open.
// The status nerdctl names is the guest's, and the case stands on it.
func TestNerdctlLosingTheExitStatusDoesNotThrowOutAProbe(t *testing.T) {
	f, s := nerdctlSuite(t)
	f.nerdctlExits = true
	well := f.answer
	f.answer = func(policy string, env, args []string, n int) outcome {
		if policy == noPolicy && caseFor(t, s, policy, env, args).id == "proxy-env" {
			hitListener(t, strings.TrimPrefix(env[0], "https_proxy=http://"))
			return probeErrorAfterConnect
		}
		return well(policy, env, args, n)
	}
	rep := run(t, s)
	if rep.failed() {
		for _, r := range rep.rows {
			if r.verdict == fail {
				t.Errorf("%s: %s", r.c.id, r.why)
			}
		}
		t.Fatalf("problems %v", rep.problems)
	}
}

// hvi passes the guest's status through, so a probe that disagrees with it
// there came from something other than the probe, and nerdctl's line is never
