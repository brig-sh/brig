// hullLinuxSuite is a suite on Linux that boots the bundle's hull, under the
// environment the bundle's brig-env.sh sets. That environment says nerdctl
// unless the shell said hull first, so it says nerdctl here: the suite has to
// put hull back.
func hullLinuxSuite(t *testing.T) (*fakeBrig, *suite) {
	t.Helper()
	f := newFake(t)
	f.versionOut = fakeLinuxHull + "\n"
	f.pinsOut = fakeHullPins
	s := newSuite(t, f)
	s.backend, s.runtime, s.brigCtl = "hull-linux", "hull", "brig-ctl"
	s.env = append(s.env, "BRIG_BOOT_ASSETS=/home/u/.local/share/brig/data/share/guest",
		"CONTAINERD_ADDRESS=unix:///run/user/1000/containerd/containerd.sock", "BRIG_RUNTIME=nerdctl")
	// hvi on PATH is the macOS backend's row. On Linux the bundle's pins
	// name the hvi urunc boots.
	s.hviPath = func() (string, error) {
		t.Error("the suite asked for hvi on PATH on hull on Linux")
		return "", errors.New("not here")
	}
	return f, s
}

// hull on Linux is what the runtime bundle ships, so the record is filed
// under the bundle's version, and names the hull, urunc, hvi and hull-assets
// the bundle pins, the kernel and initrd that booted, and the image digest
// hull reports.
func TestHullLinuxRunIsFiledUnderTheBundle(t *testing.T) {
	f, s := hullLinuxSuite(t)
	rep := run(t, s)
	if rep.failed() {
		t.Fatalf("a well-behaved guest failed on hull on Linux: %v", rep.problems)
	}
	if got := recordPath(s.backend, rep.version(), rep.variant()); got != "docs/manual-tests/egress-conformance-hull-linux-v0.1.0-rc22-rootless.md" {
		t.Errorf("filed at %q", got)
	}
	out := rep.markdown()
	for _, want := range []string{
		"# Egress conformance: hull-linux, v0.1.0-rc22, rootless\n",
		"| backend | `hull-linux` |",
		"| runtime | `" + fakeLinuxHull + "` |",
		"| runtime bundle | `v0.1.0-rc22, generic-boot, rootless` |",
		"| hull | `brig-sh/hull@" + fakeHullRef + "` |",
		"| urunc | `urunc-dev/urunc@5c6bc7060d4f6d33b0d4e8fd388f9f04cc88510b` |",
		"| hvi | `0.1.0-rc.3, commit bde7c58f0e1a2b3c4d5e6f708192a3b4c5d6e7f8` |",
		"| hull-assets | `0.1.12, from nofireai/hull-assets` |",
		"| containerd | `v2.3.5` |",
		"| rootlesskit | `v3.2.0` |",
		"| slirp4netns | `v1.3.5` |",
		"| boot assets | `a local directory, from BRIG_BOOT_ASSETS. The runtime bundle's own copy is built from " + fakeSource + "` |",
		"| image digest | `" + fakeDigest + "` |",
		"| probes ran under | `brig sh` |",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("record lacks %q:\n%s", want, out)
		}
	}
	// hull's gateway enforces the policy here, so brig's nftables table and
	// the bundle's nerdctl and monitors play no part, and a row for any of
	// them would say they did.
	for _, not := range []string{"| nftables |", "| nerdctl |", "| monitors |"} {
		if strings.Contains(out, not) {
			t.Errorf("the hull on Linux record has a %s row:\n%s", not, out)
		}
	}
	for _, c := range f.calls {
		if c[0] == "nft" {
			t.Errorf("the suite asked nft on hull on Linux: %q", c)
		}
	}
	// The digest is hull's answer, as on hvi, not nerdctl's.
	if !slices.ContainsFunc(f.calls, func(c []string) bool {
		return slices.Equal(c, []string{"hull", "inspect", sandboxName})
	}) {
		t.Errorf("hull inspect was not asked for the digest: %q", f.calls)
	}
	if n := len(f.brigCalls("exec")); n != 0 {
		t.Errorf("%d probes went through brig exec, which only nerdctl needs", n)
	}
}

// The bundle's environment says BRIG_RUNTIME=nerdctl, and brig refuses a
// BRIG_RUNTIME_BIN that is hull while it drives nerdctl. So every brig the
// suite runs is told hull, once, and no hypervisor.
func TestHullLinuxRunsBrigAsHull(t *testing.T) {
	f, s := hullLinuxSuite(t)
	if rep := run(t, s); rep.failed() {
		t.Fatalf("a well-behaved guest failed: %v", rep.problems)
	}
	n := 0
	for i, c := range f.calls {
		if c[0] != "brig" || c[1] != "run" {
			continue
		}
		n++
		env := f.envs[i]
		var kinds []string
		for _, kv := range env {
			if v, ok := strings.CutPrefix(kv, "BRIG_RUNTIME="); ok {
				kinds = append(kinds, v)
			}
		}
		if !slices.Equal(kinds, []string{"hull"}) {
			t.Errorf("brig run with BRIG_RUNTIME %q, want hull alone", kinds)
		}
		if got := envValue(env, "BRIG_RUNTIME_BIN"); got != "hull" {
			t.Errorf("brig run with BRIG_RUNTIME_BIN=%q", got)
		}
		if got := envValue(env, "BRIG_HYPERVISOR"); got != "" {
			t.Errorf("brig run with BRIG_HYPERVISOR=%q on Linux", got)
		}
	}
	if n == 0 {
		t.Fatal("no brig run")
	}
}

// The pins say which hull the bundle ships, and nothing of which hull boots.
// A run whose hull is not the bundle's would be filed under that bundle and
// pass for its evidence. It fails instead, boots nothing, and writes nothing.
// So does a run with no bundle at all: hull's tags read like the bundle's, and
// filed under its own version it would land where a bundle's record goes.
func TestAHullThatIsNotTheBundlesIsFiledUnderNoRecord(t *testing.T) {
	for name, tc := range map[string]struct {
		runtimeLine string
		pins        string
		pinsCode    int
		want        string
	}{
		"another commit": {
			"hull v0.1.1-0.20261118090000-aaaaaaaaaaaa (aaaaaaa, 2026-11-18, go1.26.8, linux/amd64)", fakeHullPins, 0,
			"reports hull commit aaaaaaa"},
		// v0.1.0-rc22 is a hull tag and the bundle's version too. Read as a
		// version it would match, so the commit is what is compared.
		"a hull tag that reads as the bundle's": {
			"hull v0.1.0-rc22 (bbbbbbb, 2026-11-18, go1.26.8, linux/amd64)", fakeHullPins, 0,
			"reports hull commit bbbbbbb"},
		"a hull that names no commit": {
			"hull v0.1.0-rc22 (go1.26.8, linux/amd64)", fakeHullPins, 0, "which names no commit"},
		"nerdctl where hull should be": {
			fakeNerdctl, fakeHullPins, 0, "which names no commit"},
		"a bundle that ships no hull": {
			fakeLinuxHull, strings.Replace(fakeHullPins, "HULL_REF="+fakeHullRef, "HULL_REF=", 1), 0,
			"pins no HULL_REF"},
		"a rootless pin of maybe": {
			fakeLinuxHull, strings.Replace(fakeHullPins, "ROOTLESS=true", "ROOTLESS=maybe", 1), 0,
			`ROOTLESS="maybe"`},
		"no bundle": {fakeLinuxHull, "", 127, "there is no bundle"},
		"pins with no bundle version": {
			fakeLinuxHull, strings.Replace(fakeHullPins, "BUNDLE_VERSION=v0.1.0-rc22\n", "", 1), 0,
			"there is no bundle"},
	} {
		t.Run(name, func(t *testing.T) {
			set := func(f *fakeBrig) {
				f.versionOut, f.pinsOut, f.pinsCode = tc.runtimeLine+"\n", tc.pins, tc.pinsCode
			}
			f, s := hullLinuxSuite(t)
			set(f)
			rep := run(t, s)
			if !rep.failed() || rep.unfiled == "" {
				t.Fatalf("the run was not refused: problems %v, unfiled %q", rep.problems, rep.unfiled)
			}
			if !strings.Contains(strings.Join(rep.problems, "\n"), tc.want) {
				t.Errorf("no problem says %q: %v", tc.want, rep.problems)
			}
			if n := len(f.brigCalls("run")); n != 0 {
				t.Errorf("booted %d sandboxes for a run that belongs under no record", n)
			}
			if rep.bundle != "" {
				t.Errorf("the record would still name bundle %q", rep.bundle)
			}

			f2, s2 := hullLinuxSuite(t)
			set(f2)
			var out, errOut bytes.Buffer
			dir := t.TempDir()
			wd, _ := os.Getwd()
			if err := os.Chdir(dir); err != nil {
				t.Fatal(err)
			}
			defer func() { _ = os.Chdir(wd) }()
			if code := runSuite(context.Background(), s2, "", &out, &errOut); code != 1 {
				t.Errorf("exit %d, want 1", code)
			}
			if !strings.Contains(out.String(), "no record written") {
				t.Errorf("the run does not say it wrote nothing:\n%s", out.String())
			}
			if _, err := os.Stat(filepath.Join(dir, "docs")); err == nil {
				t.Error("a record directory was written for a hull that is not the bundle's")
			}
		})
	}
}

// A hull built on the commit the bundle pins is the bundle's, whether Go gave
// it a tag or a pseudo-version. Either way the record is filed under the
// bundle's version, never under hull's.
func TestTheBundlesHullIsFiledUnderTheBundle(t *testing.T) {
	for name, line := range map[string]string{
		"a pseudo-version": fakeLinuxHull,
		"a tag":            "hull v0.1.0-rc23 (4bf76a6, 2026-11-16, go1.26.8, linux/amd64)",
	} {
		t.Run(name, func(t *testing.T) {
			f, s := hullLinuxSuite(t)
			f.versionOut = line + "\n"
			rep := run(t, s)
			if rep.unfiled != "" || rep.failed() {
				t.Fatalf("the bundle's own hull was refused: unfiled %q, problems %v", rep.unfiled, rep.problems)
			}
			if rep.version() != "v0.1.0-rc22" {
				t.Errorf("filed under %q, want the bundle's version", rep.version())
			}
		})
	}
}

// A node-wide install of the plain bundle shares the version of the rootless
// one, and its guests reach the network another way. Each gets its own record.
func TestHullLinuxRootlessAndPlainBundlesAreFiledApart(t *testing.T) {
	paths := map[string]string{}
	for name, rootless := range map[string]string{"rootless": "true", "plain": "false"} {
		f, s := hullLinuxSuite(t)
		f.pinsOut = strings.Replace(fakeHullPins, "ROOTLESS=true", "ROOTLESS="+rootless, 1)
		rep := run(t, s)
		paths[name] = recordPath(s.backend, rep.version(), rep.variant())
	}
	if paths["rootless"] != "docs/manual-tests/egress-conformance-hull-linux-v0.1.0-rc22-rootless.md" ||
		paths["plain"] != "docs/manual-tests/egress-conformance-hull-linux-v0.1.0-rc22.md" {
		t.Errorf("filed at %v", paths)
	}
}

// hull on Linux puts its guest behind the gateway hvi uses, so a metadata case
// the guest could not reach with no policy is unproven for hvi's reason, all
// the way into the record.
func TestHullLinuxGivesHullsUnprovenReason(t *testing.T) {
	f, s := hullLinuxSuite(t)
	well := f.answer
	f.answer = func(policy string, env, args []string, n int) outcome {
		if policy == noPolicy && caseFor(t, s, policy, env, args).id == "metadata" {
			return timedOut
		}
		return well(policy, env, args, n)
	}
	rep := run(t, s)
	if rep.failed() {
		t.Fatalf("an unproven metadata case failed the run: %v", rep.problems)
	}
	var row string
	for _, line := range strings.Split(rep.markdown(), "\n") {
		if strings.HasPrefix(line, "| `metadata` |") {
			row = line
		}
	}
	if !strings.Contains(row, "unproven") || !strings.Contains(row, "hull's gateway resets every connection to 169.254.0.0/16") {
		t.Errorf("the metadata row does not give hull's reason:\n%s", row)
	}
	if strings.Contains(row, "no metadata service") {
		t.Errorf("the hull on Linux record gives the nerdctl reason:\n%s", row)
	}
}
